    path + "/Derivative Filter", ...
    "Numerator","1-rrmDerivativeAlpha", ...
    "Denominator","[1 -rrmDerivativeAlpha]", ...
    "SampleTime","rrmSampleTime", ...
    "Position",[220 90 330 125]);
add_line(path,"Rate Error/1","Derivative Filter/1");

add_block("simulink/Math Operations/Gain",path + "/Kp", ...
    "Gain","rrmKp","Multiplication","Element-wise(K.*u)", ...
    "Position",[235 25 305 60]);
add_block("simulink/Math Operations/Gain",path + "/Ki", ...
    "Gain","rrmKi","Multiplication","Element-wise(K.*u)", ...
    "Position",[365 150 435 185]);
add_block("simulink/Math Operations/Gain",path + "/Kd", ...
    "Gain","rrmKd","Multiplication","Element-wise(K.*u)", ...
    "Position",[365 90 435 125]);
