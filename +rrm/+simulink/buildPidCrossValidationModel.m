function modelName = buildPidCrossValidationModel(modelPath)
%BUILDPIDCROSSVALIDATIONMODEL Build the native PID validation model.
arguments
    modelPath (1,1) string
end

if isempty(which("new_system"))
    error("rrm:simulink:MissingSimulink", ...
        "Simulink is required to build the cross-validation model.");
end
if ~java.io.File(char(modelPath)).isAbsolute()
    functionPath = mfilename("fullpath");
    projectRoot = fileparts(fileparts(fileparts(functionPath)));
    modelPath = fullfile(projectRoot,modelPath);
end
[parent,name,extension] = fileparts(modelPath);
if ~strcmpi(extension,".slx") || strlength(name) == 0 || ...
        ~isvarname(name)
    error("rrm:simulink:InvalidModelPath", ...
        "Model path must name a valid .slx file.");
end
if strlength(parent) == 0
    parent = ".";
end
if ~isfolder(parent)
    [created,message] = mkdir(parent);
    if ~created
        error("rrm:simulink:InvalidModelPath", ...
            "Unable to create model directory: %s", message);
    end
end
parent = string(java.io.File(char(parent)).getCanonicalPath());
modelPath = fullfile(parent,name + extension);
modelName = string(name);

if bdIsLoaded(modelName)
    close_system(modelName,0);
end
if isfile(modelPath)
    delete(modelPath);
end

new_system(modelName);
cleanup = onCleanup(@() closeIfLoaded(modelName));
set_param(modelName, ...
    "SolverType","Fixed-step", ...
    "Solver","ode4", ...
    "FixedStep","0.001", ...
    "StopTime","rrmStopTime", ...
    "SignalLogging","on", ...
    "ReturnWorkspaceOutputs","on");

addTopLevelSubsystem(modelName,"Reference",[40 100 210 250]);
addTopLevelSubsystem(modelName,"PID Controller",[280 80 470 270]);
addTopLevelSubsystem(modelName,"Two-Link Plant",[560 80 750 270]);
addTopLevelSubsystem(modelName,"Logging",[830 100 980 250]);
buildReference(modelName + "/Reference");
buildController(modelName + "/PID Controller");
buildPlant(modelName + "/Two-Link Plant");
buildLogging(modelName + "/Logging");
connectTopLevel(modelName);
assignDefaultParameters(modelName);
addModelAnnotation(modelName);
save_system(modelName,modelPath);
end

function addTopLevelSubsystem(modelName, blockName, position)
add_block("simulink/Ports & Subsystems/Subsystem", ...
    modelName + "/" + blockName, ...
    "Position",position);
end

function buildReference(path)
Simulink.SubSystem.deleteContents(path);
add_block("simulink/Sources/From Workspace",path + "/q Reference", ...
    "VariableName","rrmQReferenceSignal", ...
    "Interpolate","off", ...
    "OutputAfterFinalValue","Holding final value", ...
    "Position",[35 45 165 75]);
add_block("simulink/Sources/From Workspace",path + "/dq Reference", ...
    "VariableName","rrmDqReferenceSignal", ...
    "Interpolate","off", ...
    "OutputAfterFinalValue","Holding final value", ...
    "Position",[35 115 165 145]);
add_block("simulink/Ports & Subsystems/Out1",path + "/qRef", ...
    "Port","1","Position",[240 50 270 70]);
add_block("simulink/Ports & Subsystems/Out1",path + "/dqRef", ...
    "Port","2","Position",[240 120 270 140]);
add_line(path,"q Reference/1","qRef/1");
add_line(path,"dq Reference/1","dqRef/1");
end

