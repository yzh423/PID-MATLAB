function robot = makeRobot(name)
%MAKEROBOT Create a validated planar two-link robot configuration.
arguments
    name (1,1) string {mustBeMember(name, ...
        ["compact","baseline","extended"])} = "baseline"
end

switch name
    case "compact"
        L1 = 0.35;
        L2 = 0.25;
    case "baseline"
        L1 = 0.45;
        L2 = 0.35;
    case "extended"
        L1 = 0.55;
        L2 = 0.45;
end
m1 = 2.0;
m2 = 1.5;

robot = struct( ...
    "name", name, ...
    "L1", L1, ...
    "L2", L2, ...
    "m1", m1, ...
    "m2", m2, ...
    "payload", 0.5, ...
    "gravity", 9.81, ...
    "com", [L1; L2] / 2, ...
    "inertia", [m1*L1^2/12; m2*L2^2/12], ...
    "viscousFriction", [0.05; 0.04], ...
    "jointLimits", deg2rad([-170 170; -150 150]), ...
    "torqueLimits", [25; 15]);
end
