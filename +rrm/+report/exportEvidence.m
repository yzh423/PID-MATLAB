function validateEvidence(evidence)
modes = [
    evidence.protocol.deterministicMode
    evidence.protocol.stochasticMode
    evidence.protocol.cartesianMode
    evidence.protocol.simulinkMode
    evidence.protocol.multibodyMode
    ];
if any(modes ~= "full")
    throwAsCaller(MException("rrm:report:InvalidArtifact", ...
        "All report sources must be generated in full mode."));
end

actualCounts = [
    evidence.deterministic.runCount
    evidence.stochastic.trialCount
    evidence.cartesian.runCount
    evidence.simulink.runCount
    evidence.multibody.runCount
    ];
if ~isequal(actualCounts,[39;360;6;2;2]) || ...
        evidence.deterministic.scenarioCount ~= 13 || ...
        evidence.stochastic.scenarioCount ~= 4
    throwAsCaller(MException("rrm:report:UnexpectedStudyShape", ...
        "Formal study dimensions do not match the frozen protocol."));
end

assertUnique(evidence.deterministic.runRows,["Scenario","Controller"]);
assertUnique(evidence.stochastic.trialRows, ...
    ["Scenario","Controller","Trial"]);
assertUnique(evidence.cartesian.runRows,["Task","Controller"]);
assertUnique(evidence.simulink.runRows,"Controller");
assertUnique(evidence.multibody.runRows,"Controller");

if ~all(evidence.simulink.agreementPass) || ...
        ~all(evidence.simulink.trackingSuccess) || ...
        ~all(evidence.multibody.agreementPass) || ...
        ~all(evidence.multibody.trackingSuccess)
    throwAsCaller(MException("rrm:report:InvalidArtifact", ...
        "Independent model validation must pass the frozen acceptance gate."));
end

requiredFinite = [
    evidence.nominal.manualPid.steadyRms(:)
    evidence.nominal.fuzzyPid.steadyRms(:)
    evidence.nominal.manualPid.torqueRms(:)
    evidence.nominal.fuzzyPid.torqueRms(:)
    evidence.optimization.initialObjective
    evidence.optimization.finalObjective
    evidence.optimization.heldOutInitialObjective
    evidence.optimization.heldOutFinalObjective
    evidence.optimization.objectiveReductionPercent
    evidence.multibody.endEffectorMaxWorst
    evidence.multibody.maximumOutOfPlane
    ];
if ~all(isfinite(requiredFinite))
    throwAsCaller(MException("rrm:report:NonFiniteEvidence", ...
        "A required report value is not finite."));
end
end

function assertUnique(rows,keyVariables)
tableRows = struct2table(rows);
keyRows = unique(tableRows(:,keyVariables),'rows','stable');
if height(keyRows) ~= height(tableRows)
    throwAsCaller(MException("rrm:report:UnexpectedStudyShape", ...
        "Formal study contains duplicate key rows."));
end
end

function writeJson(outputPath,evidence)
payload = jsonencode(sanitizeForJson(evidence),'PrettyPrint',true);
temporaryPath = string(tempname(fileparts(outputPath))) + ".json";
cleanup = onCleanup(@() deleteTemporary(temporaryPath));
[fileId,message] = fopen(temporaryPath,'w','n','UTF-8');
if fileId < 0
    throwAsCaller(MException("rrm:report:InvalidOutputPath", ...
        "Could not open report evidence output: %s",message));
end
try
    fprintf(fileId,'%s\n',payload);
    fclose(fileId);
catch exception
    fclose(fileId);
    rethrow(exception);
end
[moved,message] = movefile(temporaryPath,outputPath,'f');
if ~moved
    throwAsCaller(MException("rrm:report:InvalidOutputPath", ...
        "Could not finalize report evidence output: %s",message));
end
clear cleanup;
end

