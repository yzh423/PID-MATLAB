function requireFiles(paths)
missing = paths(~arrayfun(@isfile,paths));
if ~isempty(missing)
    throwAsCaller(MException("rrm:report:MissingArtifact", ...
        "Required formal artifact is missing: %s",missing(1)));
end
end

function evidence = collectEvidence(nominal,optimization,deterministic, ...
        stochastic,cartesian,simulink,multibody,sources)
evidence = struct;
evidence.schemaVersion = 1;
timestamp = datetime("now","TimeZone","UTC", ...
    "Format","yyyy-MM-dd'T'HH:mm:ss'Z'");
evidence.generatedAt = string(timestamp);
evidence.protocol = struct( ...
    "testCount",145, ...
    "deterministicMode",deterministic.robustnessMode, ...
    "stochasticMode",stochastic.stochasticMode, ...
    "cartesianMode",cartesian.cartesianMode, ...
    "simulinkMode",simulink.simulinkValidationMode, ...
    "multibodyMode",multibody.multibodyValidationMode, ...
    "stochasticTrialsPerScenario",30);

evidence.nominal = struct( ...
    "manualPid",metricSummary(nominal.pidMetrics), ...
    "fuzzyPid",metricSummary(nominal.fuzzyMetrics));
initialObjective = optimization.nominalManualObjective;
finalObjective = optimization.nominalOptimizedObjective;
evidence.optimization = struct( ...
    "initialObjective",initialObjective, ...
    "finalObjective",finalObjective, ...
    "objectiveReductionPercent", ...
        100 * (initialObjective-finalObjective) / initialObjective, ...
    "heldOutInitialObjective",optimization.validationManualObjective, ...
    "heldOutFinalObjective",optimization.validationOptimizedObjective, ...
    "exitFlag",optimization.optimizationReport.exitFlag, ...
    "iterations",optimization.optimizationReport.solverOutput.iterations, ...
    "functionEvaluations", ...
        optimization.optimizationReport.solverOutput.funcCount);

detSummary = deterministic.summaryTable;
evidence.deterministic = struct( ...
    "mode",deterministic.robustnessMode, ...
    "runCount",height(deterministic.runTable), ...
    "scenarioCount",numel(unique(deterministic.runTable.Scenario)), ...
    "successCount",controllerValues(detSummary,"SuccessCount"), ...
    "successRate",controllerValues(detSummary,"SuccessRate"), ...
    "failureCount",controllerValues(detSummary,"FailedRunCount"), ...
    "summaryRows",table2struct(detSummary), ...
    "runRows",table2struct(deterministic.runTable));

stoSummary = stochastic.summaryTable;
combined = stoSummary(stoSummary.Scenario == "combined-stochastic",:);
highNoise = stoSummary(stoSummary.Scenario == "noise-high",:);
evidence.stochastic = struct( ...
    "mode",stochastic.stochasticMode, ...
    "trialCount",height(stochastic.trialTable), ...
    "scenarioCount",numel(unique(stochastic.trialTable.Scenario)), ...
    "combinedSuccessCount",controllerValues(combined,"SuccessCount"), ...
    "highNoiseMeanTorqueSlew",controllerValues(highNoise,"MeanTorqueSlew"), ...
    "summaryRows",table2struct(stoSummary), ...
    "trialRows",table2struct(stochastic.trialTable));

evidence.cartesian = struct( ...
    "mode",cartesian.cartesianMode, ...
    "runCount",height(cartesian.runTable), ...
    "successCount",sum(cartesian.runTable.Success), ...
    "runRows",table2struct(cartesian.runTable));
evidence.simulink = validationSummary(simulink.runTable, ...
    "SimulinkTrackingSuccess");
evidence.simulink.mode = simulink.simulinkValidationMode;
evidence.simulink.rigidBodyMaxMassMatrixError = ...
    simulink.dynamicsReport.maxMassMatrixError;
evidence.simulink.rigidBodyMaxVelocityProductError = ...
    simulink.dynamicsReport.maxVelocityProductError;
evidence.simulink.rigidBodyMaxGravityError = ...
    simulink.dynamicsReport.maxGravityError;
evidence.multibody = validationSummary(multibody.runTable, ...
    "MultibodyTrackingSuccess");
evidence.multibody.mode = multibody.multibodyValidationMode;
evidence.multibody.maximumOutOfPlane = ...
    max(multibody.runTable.MaximumOutOfPlane);
evidence.multibody.endEffectorMaxWorst = ...
    max(multibody.runTable.EndEffectorMax);

evidence.artifacts = selectedArtifacts(sources.absolutePath(1));
evidence.sources = table2struct(sources(:,["name","relativePath"]));
end

function summary = metricSummary(metrics)
summary = struct( ...
    "rmsError",metrics.rmsError, ...
    "maxError",metrics.maxAbsError, ...
    "steadyRms",metrics.steadyStateRmsError, ...
    "steadyMax",metrics.steadyStateMaxAbsError, ...
    "torqueRms",metrics.controlRms, ...
    "controlEnergy",metrics.controlEnergy, ...
    "saturationTime",metrics.saturationTime, ...
    "success",logical(metrics.success));
end

function values = controllerValues(summaryTable,variableName)
expected = ["manual-pid";"mamdani-fuzzy-pid";"optimization-pid"];
if height(summaryTable) ~= numel(expected) || ...
        ~isequal(string(summaryTable.Controller(:)),expected)
    throwAsCaller(MException("rrm:report:UnexpectedStudyShape", ...
        "Controller rows do not match the frozen protocol."));
end
column = summaryTable.(variableName);
values = struct( ...
    "manualPid",column(1), ...
    "fuzzyPid",column(2), ...
    "optimizedPid",column(3));
end

function summary = validationSummary(runTable,trackingVariable)
summary = struct( ...
    "runCount",height(runTable), ...
    "agreementPass",logical(runTable.AgreementPass), ...
    "trackingSuccess",logical(runTable.(trackingVariable)), ...
    "runRows",table2struct(runTable));
end

