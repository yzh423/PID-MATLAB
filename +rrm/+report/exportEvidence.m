function evidence = exportEvidence(projectRoot,outputPath)
%EXPORTEVIDENCE Validate formal results and export report evidence as JSON.
arguments
    projectRoot (1,1) string
    outputPath (1,1) string
end

projectRoot = canonicalDirectory(projectRoot);
outputPath = canonicalOutputPath(outputPath);
sources = requiredSources(projectRoot);
requireFiles(sources.absolutePath);

nominal = load(sources.absolutePath(1),"pidMetrics","fuzzyMetrics");
optimization = load(sources.absolutePath(2), ...
    "optimizationReport","nominalManualObjective", ...
    "nominalOptimizedObjective","validationManualObjective", ...
    "validationOptimizedObjective");
deterministic = load(sources.absolutePath(3), ...
    "robustnessMode","runTable","summaryTable");
stochastic = load(sources.absolutePath(4), ...
    "stochasticMode","trialTable","summaryTable");
cartesian = load(sources.absolutePath(5),"cartesianMode","runTable");
simulink = load(sources.absolutePath(6), ...
    "simulinkValidationMode","runTable","dynamicsReport");
multibody = load(sources.absolutePath(7), ...
    "multibodyValidationMode","runTable");
validateCsvSources(sources,deterministic,stochastic,cartesian, ...
    simulink,multibody);

evidence = collectEvidence(nominal,optimization,deterministic, ...
    stochastic,cartesian,simulink,multibody,sources);
validateEvidence(evidence);
writeJson(outputPath,evidence);
evidence.outputPath = outputPath;
end

function validateCsvSources(sources,deterministic,stochastic,cartesian, ...
        simulink,multibody)
validateCsvMirror(deterministic.runTable,sources.absolutePath(8), ...
    ["Scenario","Controller"], ...
    ["Success","JointRmsMean","EndEffectorMax", ...
     "TotalSaturationTime"]);
validateCsvMirror(deterministic.summaryTable,sources.absolutePath(9), ...
    "Controller",["SuccessCount","SuccessRate", ...
    "WorstEndEffectorMax"]);
validateCsvMirror(stochastic.trialTable,sources.absolutePath(10), ...
    ["Scenario","Controller","Trial"], ...
    ["Success","JointRmsMean","TorqueSlewMean", ...
     "TotalSaturationTime"]);
validateCsvMirror(stochastic.summaryTable,sources.absolutePath(11), ...
    ["Scenario","Controller"], ...
    ["SuccessCount","SuccessRate","MeanTorqueSlew"]);
validateCsvMirror(cartesian.runTable,sources.absolutePath(12), ...
    ["Task","Controller"], ...
    ["Success","CartesianRms","CartesianMax"]);
validateCsvMirror(simulink.runTable,sources.absolutePath(13), ...
    "Controller",["AgreementPass","SimulinkTrackingSuccess", ...
    "QRmsJ1","QRmsJ2"]);
validateCsvMirror(multibody.runTable,sources.absolutePath(14), ...
    "Controller",["AgreementPass","MultibodyTrackingSuccess", ...
    "EndEffectorMax","MaximumOutOfPlane"]);
end

function validateCsvMirror(sourceTable,csvPath,keyVariables,valueVariables)
csvTable = readtable(csvPath,'TextType','string', ...
    'VariableNamingRule','preserve');
if height(csvTable) ~= height(sourceTable) || ...
        ~isequal(string(csvTable.Properties.VariableNames), ...
        string(sourceTable.Properties.VariableNames))
    throwAsCaller(MException("rrm:report:UnexpectedStudyShape", ...
        "CSV artifact shape does not match its MAT source: %s",csvPath));
end
for variable = keyVariables
    if ~isequal(string(csvTable.(variable)), ...
            string(sourceTable.(variable)))
        throwAsCaller(MException("rrm:report:UnexpectedStudyShape", ...
            "CSV key rows do not match the MAT source: %s",csvPath));
    end
end
for variable = valueVariables
    csvValues = double(csvTable.(variable));
    sourceValues = double(sourceTable.(variable));
    tolerance = 1e-12 .* max(1,abs(sourceValues));
    matching = (abs(csvValues-sourceValues) <= tolerance) | ...
        (isnan(csvValues) & isnan(sourceValues)) | ...
        (isinf(csvValues) & csvValues == sourceValues);
    if ~all(matching)
        throwAsCaller(MException("rrm:report:InvalidArtifact", ...
            "CSV values do not match the MAT source: %s",csvPath));
    end
end
end

function directory = canonicalDirectory(directory)
if ~isfolder(directory)
    throwAsCaller(MException("rrm:report:InvalidArtifact", ...
        "Project root does not exist: %s",directory));
end
directory = string(java.io.File(char(directory)).getCanonicalPath());
end

function outputPath = canonicalOutputPath(outputPath)
[parent,name,extension] = fileparts(outputPath);
parent = string(parent);
if strlength(parent) == 0
    parent = string(pwd);
end
if strlength(name) == 0 || ~strcmpi(extension,".json") || ~isfolder(parent)
    throwAsCaller(MException("rrm:report:InvalidOutputPath", ...
        "Output path must name a JSON file in an existing directory: %s", ...
        outputPath));
end
parent = string(java.io.File(char(parent)).getCanonicalPath());
outputPath = fullfile(parent,string(name) + string(extension));
end

