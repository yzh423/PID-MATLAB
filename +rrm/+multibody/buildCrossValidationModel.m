end

function connectPhysicalPlant(path)
add_line(path,"tau/1","Torque Split/1");
add_line(path,"Torque Split/1","Torque 1/1");
add_line(path,"Torque Split/2","Torque 2/1");
for joint = 1:2
    add_line(path,"Position "+joint+"/1", ...
        "Position Vector/"+joint);
    add_line(path,"Velocity "+joint+"/1", ...
        "Velocity Vector/"+joint);
    jointPath = path + "/Revolute Joint " + joint;
    connectPorts(path,path+"/Torque "+joint,"RConn",1, ...
        jointPath,"LConn",2);
    connectPorts(path,jointPath,"RConn",2, ...
        path+"/Position "+joint,"LConn",1);
    connectPorts(path,jointPath,"RConn",3, ...
        path+"/Velocity "+joint,"LConn",1);
end
add_line(path,"Position Vector/1","q/1");
add_line(path,"Velocity Vector/1","dq/1");

coordinateNames = ["X","Y","Z"];
for coordinate = 1:3
    connectPorts(path,path+"/End Effector Sensor","RConn",coordinate+1, ...
        path+"/End Effector "+coordinateNames(coordinate),"LConn",1);
    add_line(path,"End Effector "+coordinateNames(coordinate)+"/1", ...
        "End Effector Vector/"+coordinate);
end
add_line(path,"End Effector Vector/1","endEffectorPosition/1");

world = path + "/World Frame";
joint1 = path + "/Revolute Joint 1";
joint2 = path + "/Revolute Joint 2";
connectPorts(path,world,"RConn",1,joint1,"LConn",1);
connectPorts(path,world,"RConn",1, ...
    path+"/Mechanism Configuration","RConn",1);
connectPorts(path,world,"RConn",1, ...
    path+"/Solver Configuration","RConn",1);
connectPorts(path,world,"RConn",1,path+"/Base Transform","LConn",1);
connectPorts(path,path+"/Base Transform","RConn",1, ...
    path+"/Base Solid","RConn",1);

connectPorts(path,joint1,"RConn",1, ...
    path+"/Link 1 Center Transform","LConn",1);
connectPorts(path,path+"/Link 1 Center Transform","RConn",1, ...
    path+"/Link 1 Solid","RConn",1);
connectPorts(path,joint1,"RConn",1, ...
    path+"/Link 1 Distal Transform","LConn",1);
connectPorts(path,path+"/Link 1 Distal Transform","RConn",1, ...
    joint2,"LConn",1);

connectPorts(path,joint2,"RConn",1, ...
    path+"/Link 2 Center Transform","LConn",1);
connectPorts(path,path+"/Link 2 Center Transform","RConn",1, ...
    path+"/Link 2 Solid","RConn",1);
connectPorts(path,joint2,"RConn",1, ...
    path+"/Link 2 Distal Transform","LConn",1);
connectPorts(path,path+"/Link 2 Distal Transform","RConn",1, ...
    path+"/Payload Inertia","RConn",1);
connectPorts(path,world,"RConn",1, ...
    path+"/End Effector Sensor","LConn",1);
connectPorts(path,path+"/Link 2 Distal Transform","RConn",1, ...
    path+"/End Effector Sensor","RConn",1);
end

function connectPorts(system,sourceBlock,sourceSide,sourceIndex, ...
        destinationBlock,destinationSide,destinationIndex)
sourcePorts = get_param(sourceBlock,"PortHandles");
destinationPorts = get_param(destinationBlock,"PortHandles");
add_line(system,sourcePorts.(sourceSide)(sourceIndex), ...
    destinationPorts.(destinationSide)(destinationIndex), ...
    "autorouting","smart");
end

function addRigidTransform(path,name,offset,position)
blockPath = path + "/" + name;
add_block(libraryBlock("sm_lib","Rigid Transform"),blockPath, ...
    "TranslationMethod","Cartesian", ...
    "TranslationCartesianOffset",offset, ...
    "TranslationCartesianOffsetUnits","m", ...
    "Position",position);
end

function color = linkColor(joint)
if joint == 1
    color = "[0.12 0.45 0.78]";
else
    color = "[0.15 0.68 0.42]";
end
end

function source = libraryBlock(library,name)
load_system(library);
matches = find_system(library, ...
    "LookUnderMasks","all", ...
    "FollowLinks","on", ...
    "Name",name);
if numel(matches) ~= 1
    error("rrm:multibody:MissingLibraryBlock", ...
        "Expected exactly one %s block in %s.",name,library);
end
source = string(matches{1});
end

function buildLogging(path)
Simulink.SubSystem.deleteContents(path);
names = ["q","dq","tau","tau_u","endEffectorPosition"];
for index = 1:numel(names)
    y = 30 + (index-1)*50;
    add_block("simulink/Ports & Subsystems/In1", ...
        path + "/" + names(index), ...
        "Port",string(index),"Position",[20 y 50 y+20]);
    add_block("simulink/Sinks/Terminator", ...
        path + "/End " + names(index), ...
        "Position",[130 y 150 y+20]);
    add_line(path,names(index)+"/1","End "+names(index)+"/1");
end
end

function connectTopLevel(modelName)
add_line(modelName,"Reference/1","PID Controller/1");
add_line(modelName,"Reference/2","PID Controller/2");
qLine = add_line(modelName,"Multibody Plant/1", ...
    "PID Controller/3","autorouting","smart");
add_line(modelName,"Multibody Plant/1","Logging/1", ...
    "autorouting","smart");
dqLine = add_line(modelName,"Multibody Plant/2", ...
    "PID Controller/4","autorouting","smart");
add_line(modelName,"Multibody Plant/2","Logging/2", ...
    "autorouting","smart");
tauLine = add_line(modelName,"PID Controller/1", ...
    "Multibody Plant/1","autorouting","smart");
add_line(modelName,"PID Controller/1","Logging/3", ...
    "autorouting","smart");
tauUnsaturatedLine = add_line(modelName,"PID Controller/2", ...
    "Logging/4","autorouting","smart");
endEffectorLine = add_line(modelName,"Multibody Plant/3", ...
    "Logging/5","autorouting","smart");
configureLoggedSignal(qLine,"q");
configureLoggedSignal(dqLine,"dq");
configureLoggedSignal(tauLine,"tau");
configureLoggedSignal(tauUnsaturatedLine,"tauUnsaturated");
configureLoggedSignal(endEffectorLine,"endEffectorPosition");
end

function configureLoggedSignal(lineHandle,name)
displayName = name;
if name == "tauUnsaturated"
    displayName = "tau_u";
elseif name == "endEffectorPosition"
    displayName = "xyz";
end
set_param(lineHandle,"Name",displayName);
sourcePort = get_param(lineHandle,"SrcPortHandle");
set_param(sourcePort, ...
    "DataLogging","on", ...
    "DataLoggingNameMode","Custom", ...
    "DataLoggingName",name);
end

function closeSource(modelName,wasLoaded)
if ~wasLoaded
    closeIfLoaded(modelName);
end
end

function closeIfLoaded(modelName)
if bdIsLoaded(modelName)
    close_system(modelName,0);
end
end
