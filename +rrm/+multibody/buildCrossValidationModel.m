for coordinate = 1:3
    add_block(libraryBlock("nesl_utility","PS-Simulink Converter"), ...
        path + "/End Effector " + coordinateNames(coordinate), ...
        "Unit","m", ...
        "Position",[785 565+coordinate*35 835 590+coordinate*35]);
