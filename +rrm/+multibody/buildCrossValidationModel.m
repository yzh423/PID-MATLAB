add_block("simulink/Ports & Subsystems/In1",path + "/tau", ...
    "Port","1","Position",[20 40 50 60]);
add_block("simulink/Signal Routing/Demux",path + "/Torque Split", ...
    "Outputs","2","Position",[80 25 85 100]);

for joint = 1:2
    y = 25 + (joint-1)*70;
    add_block(libraryBlock("nesl_utility","Simulink-PS Converter"), ...
        path + "/Torque " + joint, ...
        "Unit","N*m","Position",[125 y 175 y+30]);
    add_block(libraryBlock("nesl_utility","PS-Simulink Converter"), ...
        path + "/Position " + joint, ...
        "Unit","rad","Position",[785 y 835 y+30]);
