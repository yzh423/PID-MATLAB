        path + "/Velocity " + joint, ...
        "Unit","rad/s","Position",[785 y+35 835 y+65]);
    jointPath = path + "/Revolute Joint " + joint;
    add_block(libraryBlock("sm_lib","Revolute Joint"),jointPath, ...
        "Position",[300 y 360 y+65]);
    set_param(jointPath, ...
        "TorqueActuationMode","InputTorque", ...
        "MotionActuationMode","ComputedMotion", ...
        "SensePosition","on", ...
        "SenseVelocity","on", ...
        "PositionTargetSpecify","on", ...
        "PositionTargetPriority","High", ...
        "PositionTargetValue",sprintf("rrmInitialQ(%d)",joint), ...
        "PositionTargetValueUnits","rad", ...
        "VelocityTargetSpecify","on", ...
        "VelocityTargetPriority","High", ...
        "VelocityTargetValue",sprintf("rrmInitialDq(%d)",joint), ...
        "VelocityTargetValueUnits","rad/s", ...
        "DampingCoefficient",sprintf("rrmMbDamping(%d)",joint), ...
        "DampingCoefficientUnits","N*m/(rad/s)");
end

add_block("simulink/Signal Routing/Mux",path + "/Position Vector", ...
    "Inputs","2","Position",[880 30 885 95]);
add_block("simulink/Signal Routing/Mux",path + "/Velocity Vector", ...
    "Inputs","2","Position",[880 115 885 180]);
add_block("simulink/Ports & Subsystems/Out1",path + "/q", ...
    "Port","1","Position",[940 55 970 75]);
add_block("simulink/Ports & Subsystems/Out1",path + "/dq", ...
    "Port","2","Position",[940 140 970 160]);
add_block("simulink/Signal Routing/Mux",path + "/End Effector Vector", ...
    "Inputs","3","Position",[880 220 885 310]);
add_block("simulink/Ports & Subsystems/Out1", ...
    path + "/endEffectorPosition", ...
    "Port","3","Position",[940 255 970 275]);

add_block(libraryBlock("sm_lib","World Frame"),path + "/World Frame", ...
    "Position",[20 365 70 415]);
add_block(libraryBlock("sm_lib","Mechanism Configuration"), ...
    path + "/Mechanism Configuration", ...
    "UniformGravity","Constant", ...
    "GravityVector","[0 -rrmGravity 0]", ...
    "GravityVectorUnits","m/s^2", ...
    "Position",[20 445 100 495]);
add_block(libraryBlock("nesl_utility","Solver Configuration"), ...
    path + "/Solver Configuration", ...
    "Position",[20 520 90 570]);

addRigidTransform(path,"Base Transform","[0 0 -0.04]",[125 365 195 415]);
add_block(libraryBlock("sm_lib","Brick Solid"),path + "/Base Solid", ...
    "BrickDimensions","[0.14 0.14 0.08]", ...
    "BrickDimensionsUnits","m", ...
    "BasedOnType","Mass", ...
    "Mass","5", ...
    "MassUnits","kg", ...
    "GraphicDiffuseColor","[0.22 0.24 0.28]", ...
    "Position",[225 365 295 415]);

for joint = 1:2
    y = 365 + (joint-1)*120;
    addRigidTransform(path,"Link "+joint+" Center Transform", ...
        sprintf("[rrmMbLinkLength(%d)/2 0 0]",joint), ...
        [410 y 490 y+45]);
    addRigidTransform(path,"Link "+joint+" Distal Transform", ...
        sprintf("[rrmMbLinkLength(%d) 0 0]",joint), ...
        [410 y+55 490 y+100]);
    solidPath = path + "/Link " + joint + " Solid";
    add_block(libraryBlock("sm_lib","Brick Solid"),solidPath, ...
        "BrickDimensions",sprintf( ...
        "[rrmMbLinkLength(%d) rrmMbWidth rrmMbWidth]",joint), ...
        "BrickDimensionsUnits","m", ...
        "InertiaType","Custom", ...
        "Mass",sprintf("rrmMbLinkMass(%d)",joint), ...
        "MassUnits","kg", ...
        "CenterOfMass","[0 0 0]", ...
        "CenterOfMassUnits","m", ...
        "MomentsOfInertia",sprintf("rrmMbMoments(%d,:)",joint), ...
        "MomentsOfInertiaUnits","kg*m^2", ...
        "ProductsOfInertia","[0 0 0]", ...
        "ProductsOfInertiaUnits","kg*m^2", ...
        "GraphicDiffuseColor",linkColor(joint), ...
        "Position",[545 y 615 y+45]);
end

add_block(libraryBlock("sm_lib","Inertia"),path + "/Payload Inertia", ...
    "InertiaType","PointMass", ...
    "Mass","rrmMbPayload", ...
    "MassUnits","kg", ...
    "GraphicType","Marker", ...
    "MarkerShape","Sphere", ...
    "MarkerSize","0.075", ...
    "GraphicDiffuseColor","[0.82 0.18 0.16]", ...
    "Position",[660 500 735 545]);
