%RUN_SIMULINK_CROSS_VALIDATION Cross-check MATLAB and Simulink PID runs.
projectRoot = fileparts(fileparts(mfilename("fullpath")));
addpath(projectRoot);
if ~exist("outputRoot","var")
    outputRoot = fullfile(projectRoot,"results");
end
if ~exist("simulinkValidationMode","var")
    simulinkValidationMode = "full";
end
if ~any(simulinkValidationMode == ["full","smoke"])
    error("rrm:experiment:InvalidSimulinkValidationMode", ...
        "Simulink validation mode must be full or smoke.");
end

dataDirectory = fullfile(outputRoot,"data");
figureDirectory = fullfile(outputRoot,"figures");
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

robot = rrm.config.makeRobot("baseline");
simulationOptions = rrm.config.makeSimulationOptions();
if simulinkValidationMode == "full"
    moveDuration = 3;
    totalDuration = 5;
else
    moveDuration = 0.08;
    totalDuration = 0.12;
end
reference = rrm.trajectory.quintic( ...
    [0;0],deg2rad([45;60]),moveDuration, ...
    simulationOptions.sampleTime,totalDuration);
modelPath = fullfile(projectRoot,"models", ...
    "rrm_pid_cross_validation.slx");
dynamicsReport = rrm.validation.compareRigidBodyDynamics(robot);

controllerDefinitions(1) = struct( ...
    "name","manual-pid", ...
    "controller",rrm.config.makePidController(robot));
controllerDefinitions(2) = struct( ...
    "name","optimization-pid", ...
    "controller",rrm.config.makeOptimizedPidController(robot));

emptyRun = struct( ...
    "controllerName","", ...
    "matlabResult",struct(), ...
    "simulinkResult",struct(), ...
    "comparison",struct(), ...
    "matlabMetrics",struct(), ...
    "simulinkMetrics",struct());
runs = repmat(emptyRun,numel(controllerDefinitions),1);
emptyRow = struct( ...
    "Controller","", ...
    "MatlabStatus","", ...
    "SimulinkStatus","", ...
    "AgreementPass",false, ...
    "SimulinkTrackingSuccess",false, ...
    "QRmsJ1",NaN,"QRmsJ2",NaN, ...
    "QMaxJ1",NaN,"QMaxJ2",NaN, ...
    "DqRmsJ1",NaN,"DqRmsJ2",NaN, ...
    "DqMaxJ1",NaN,"DqMaxJ2",NaN, ...
    "TauRmsJ1",NaN,"TauRmsJ2",NaN, ...
    "TauMaxJ1",NaN,"TauMaxJ2",NaN, ...
    "MatlabSaturationJ1",NaN,"MatlabSaturationJ2",NaN, ...
    "SimulinkSaturationJ1",NaN,"SimulinkSaturationJ2",NaN, ...
    "SimulinkSteadyRmsJ1",NaN,"SimulinkSteadyRmsJ2",NaN, ...
    "SimulinkSteadyMaxJ1",NaN,"SimulinkSteadyMaxJ2",NaN);
rows = repmat(emptyRow,numel(controllerDefinitions),1);

for index = 1:numel(controllerDefinitions)
    definition = controllerDefinitions(index);
    matlabResult = rrm.simulation.runController( ...
        robot,definition.controller,reference,simulationOptions);
    simulinkResult = rrm.simulink.runPidCrossValidation( ...
        robot,definition.controller,reference,simulationOptions,modelPath);
    comparison = rrm.simulink.comparePidRuns(matlabResult,simulinkResult);
    matlabMetrics = rrm.metrics.evaluate( ...
        matlabResult,simulationOptions.successCriteria);
    simulinkMetrics = rrm.metrics.evaluate( ...
        simulinkResult,simulationOptions.successCriteria);
    runs(index) = struct( ...
        "controllerName",definition.name, ...
        "matlabResult",matlabResult, ...
        "simulinkResult",simulinkResult, ...
        "comparison",comparison, ...
        "matlabMetrics",matlabMetrics, ...
        "simulinkMetrics",simulinkMetrics);
    rows(index) = makeRow(definition.name,matlabResult,simulinkResult, ...
        comparison,simulinkMetrics);
end
runTable = struct2table(rows);

save(fullfile(dataDirectory,"simulink_cross_validation.mat"), ...
    "simulinkValidationMode","robot","simulationOptions", ...
    "reference","modelPath","dynamicsReport", ...
    "controllerDefinitions","runs","runTable");
writetable(runTable,fullfile(dataDirectory, ...
    "simulink_cross_validation_runs.csv"));

writeFigure(trackingFigure(runs),figureDirectory,"tracking");
writeFigure(differenceFigure(runs),figureDirectory,"differences");
writeFigure(torqueFigure(runs,robot),figureDirectory,"torque");
writeFigure(summaryFigure(runs),figureDirectory,"summary");

disp(runTable);
fprintf("Simulink validation mode: %s; runs: %d; agreements: %d\n", ...
    simulinkValidationMode,height(runTable),nnz(runTable.AgreementPass));
fprintf("Rigid-body maxima M=%0.3g, C*dq=%0.3g, G=%0.3g\n", ...
    dynamicsReport.maxMassMatrixError, ...
    dynamicsReport.maxVelocityProductError, ...
    dynamicsReport.maxGravityError);
assert(height(runTable) == 2 && ...
    numel(unique(runTable.Controller)) == 2 && ...
    all(runTable.AgreementPass), ...
    "rrm:experiment:FailedSimulinkAgreement", ...
    "Both frozen PID controllers must pass numerical cross-validation.");
if simulinkValidationMode == "full"
    assert(all(runTable.SimulinkTrackingSuccess), ...
        "rrm:experiment:FailedSimulinkTracking", ...
        "Formal Simulink runs must satisfy unchanged tracking criteria.");
end

function row = makeRow(name,matlabResult,simulinkResult,comparison,metrics)
row = struct( ...
    "Controller",name, ...
    "MatlabStatus",matlabResult.status, ...
    "SimulinkStatus",simulinkResult.status, ...
    "AgreementPass",comparison.pass, ...
    "SimulinkTrackingSuccess",metrics.success, ...
    "QRmsJ1",comparison.qRmsDifference(1), ...
    "QRmsJ2",comparison.qRmsDifference(2), ...
    "QMaxJ1",comparison.qMaxDifference(1), ...
    "QMaxJ2",comparison.qMaxDifference(2), ...
    "DqRmsJ1",comparison.dqRmsDifference(1), ...
    "DqRmsJ2",comparison.dqRmsDifference(2), ...
    "DqMaxJ1",comparison.dqMaxDifference(1), ...
    "DqMaxJ2",comparison.dqMaxDifference(2), ...
    "TauRmsJ1",comparison.tauRmsDifference(1), ...
    "TauRmsJ2",comparison.tauRmsDifference(2), ...
    "TauMaxJ1",comparison.tauMaxDifference(1), ...
    "TauMaxJ2",comparison.tauMaxDifference(2), ...
    "MatlabSaturationJ1",comparison.matlabSaturationTime(1), ...
    "MatlabSaturationJ2",comparison.matlabSaturationTime(2), ...
    "SimulinkSaturationJ1",comparison.simulinkSaturationTime(1), ...
    "SimulinkSaturationJ2",comparison.simulinkSaturationTime(2), ...
    "SimulinkSteadyRmsJ1",metrics.steadyStateRmsError(1), ...
    "SimulinkSteadyRmsJ2",metrics.steadyStateRmsError(2), ...
    "SimulinkSteadyMaxJ1",metrics.steadyStateMaxAbsError(1), ...
    "SimulinkSteadyMaxJ2",metrics.steadyStateMaxAbsError(2));
end

function figureHandle = trackingFigure(runs)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 720]);
layout = tiledlayout(figureHandle,2,2, ...
    "TileSpacing","compact","Padding","compact");
for runIndex = 1:numel(runs)
    for joint = 1:2
        axisHandle = nexttile(layout);
        run = runs(runIndex);
        plot(axisHandle,run.matlabResult.time, ...
            rad2deg(run.matlabResult.qReference(joint,:)), ...
            ":k","LineWidth",1.4,"DisplayName","reference");
        hold(axisHandle,"on");
        plot(axisHandle,run.matlabResult.time, ...
            rad2deg(run.matlabResult.q(joint,:)), ...
            "LineWidth",1.2,"DisplayName","MATLAB RK4");
        plot(axisHandle,run.simulinkResult.time, ...
            rad2deg(run.simulinkResult.q(joint,:)), ...
            "--","LineWidth",1.1,"DisplayName","Simulink ode4");
        grid(axisHandle,"on");
        xlabel(axisHandle,"Time (s)");
        ylabel(axisHandle,sprintf("q_%d (deg)",joint));
        title(axisHandle,run.controllerName+" joint "+joint);
        legend(axisHandle,"Location","best");
    end
end
title(layout,"MATLAB and Simulink Joint Tracking");
end

function figureHandle = differenceFigure(runs)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 720]);
layout = tiledlayout(figureHandle,2,2, ...
    "TileSpacing","compact","Padding","compact");
for runIndex = 1:numel(runs)
    run = runs(runIndex);
    axisHandle = nexttile(layout);
    semilogy(axisHandle,run.matlabResult.time, ...
        max(abs(run.comparison.qDifference),eps),"LineWidth",1.1);
    hold(axisHandle,"on");
    yline(axisHandle,run.comparison.thresholds.qMax,"--k", ...
        "q max threshold","LabelHorizontalAlignment","left");
    grid(axisHandle,"on");
    xlabel(axisHandle,"Time (s)");
    ylabel(axisHandle,"|Delta q| (rad)");
    title(axisHandle,run.controllerName+" position");
    legend(axisHandle,["joint 1","joint 2"],"Location","best");

    axisHandle = nexttile(layout);
    semilogy(axisHandle,run.matlabResult.time, ...
        max(abs(run.comparison.dqDifference),eps),"LineWidth",1.1);
    hold(axisHandle,"on");
    yline(axisHandle,run.comparison.thresholds.dqRms,"--k", ...
        "dq RMS threshold","LabelHorizontalAlignment","left");
    grid(axisHandle,"on");
    xlabel(axisHandle,"Time (s)");
    ylabel(axisHandle,"|Delta dq| (rad/s)");
    title(axisHandle,run.controllerName+" velocity");
    legend(axisHandle,["joint 1","joint 2"],"Location","best");
end
title(layout,"Absolute MATLAB-Simulink Differences");
end

function figureHandle = torqueFigure(runs,robot)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 720]);
layout = tiledlayout(figureHandle,2,2, ...
    "TileSpacing","compact","Padding","compact");
for runIndex = 1:numel(runs)
    for joint = 1:2
        axisHandle = nexttile(layout);
        run = runs(runIndex);
        plot(axisHandle,run.matlabResult.time, ...
            run.matlabResult.tau(joint,:),"LineWidth",1.2, ...
            "DisplayName","MATLAB RK4");
        hold(axisHandle,"on");
        plot(axisHandle,run.simulinkResult.time, ...
            run.simulinkResult.tau(joint,:),"--","LineWidth",1.1, ...
            "DisplayName","Simulink ode4");
        yline(axisHandle,robot.torqueLimits(joint),":k", ...
            "HandleVisibility","off");
        yline(axisHandle,-robot.torqueLimits(joint),":k", ...
            "HandleVisibility","off");
        grid(axisHandle,"on");
        xlabel(axisHandle,"Time (s)");
        ylabel(axisHandle,sprintf("tau_%d (N m)",joint));
        title(axisHandle,run.controllerName+" joint "+joint);
        legend(axisHandle,"Location","best");
    end
end
title(layout,"Applied Torque Agreement and Limits");
end

function figureHandle = summaryFigure(runs)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1050 440]);
layout = tiledlayout(figureHandle,1,2, ...
    "TileSpacing","compact","Padding","compact");
labels = ["q RMS","q max","dq RMS","tau RMS"];
for runIndex = 1:numel(runs)
    axisHandle = nexttile(layout);
    comparison = runs(runIndex).comparison;
    normalized = [ ...
        max(comparison.qRmsDifference)/comparison.thresholds.qRms; ...
        max(comparison.qMaxDifference)/comparison.thresholds.qMax; ...
        max(comparison.dqRmsDifference)/comparison.thresholds.dqRms; ...
        max(comparison.tauRmsDifference)/comparison.thresholds.tauRms];
    bar(axisHandle,normalized,0.65);
    hold(axisHandle,"on");
    yline(axisHandle,1,"--r","acceptance boundary");
    set(axisHandle,"YScale","log");
    xticks(axisHandle,1:numel(labels));
    xticklabels(axisHandle,labels);
    xtickangle(axisHandle,20);
    ylabel(axisHandle,"Measured difference / threshold");
    title(axisHandle,runs(runIndex).controllerName);
    grid(axisHandle,"on");
end
title(layout,"Normalized Cross-Validation Margin (< 1 passes)");
end

function writeFigure(figureHandle,figureDirectory,suffix)
exportgraphics(figureHandle,fullfile(figureDirectory, ...
    "simulink_cross_validation_"+suffix+".png"), ...
    "Resolution",300);
close(figureHandle);
end
