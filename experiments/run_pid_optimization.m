%RUN_PID_OPTIMIZATION Tune PID on nominal data and validate frozen gains.
projectRoot = fileparts(fileparts(mfilename("fullpath")));
addpath(projectRoot);
if ~exist("outputRoot","var")
    outputRoot = fullfile(projectRoot,"results");
end

dataDirectory = fullfile(outputRoot,"data");
figureDirectory = fullfile(outputRoot,"figures");
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

trainingRobot = rrm.config.makeRobot("baseline");
validationRobot = trainingRobot;
validationRobot.name = "held-out-payload-0.8kg";
validationRobot.payload = 0.8;
manualController = rrm.config.makePidController(trainingRobot);
optimizationConfiguration = ...
    rrm.config.makePidOptimization(manualController);
simulationOptions = rrm.config.makeSimulationOptions();
reference = rrm.trajectory.quintic( ...
    [0;0],deg2rad([45;60]),3,simulationOptions.sampleTime,5);

optimizationReport = rrm.optimization.tunePid( ...
    trainingRobot,manualController,reference, ...
    simulationOptions,optimizationConfiguration);
optimizedController = optimizationReport.controller;

nominalManualResult = rrm.simulation.runPid( ...
    trainingRobot,manualController,reference,simulationOptions);
nominalOptimizedResult = rrm.simulation.runPid( ...
    trainingRobot,optimizedController,reference,simulationOptions);
[nominalManualObjective,nominalManualComponents] = ...
    rrm.optimization.scorePidResult(nominalManualResult, ...
    trainingRobot,reference,optimizationConfiguration);
[nominalOptimizedObjective,nominalOptimizedComponents] = ...
    rrm.optimization.scorePidResult(nominalOptimizedResult, ...
    trainingRobot,reference,optimizationConfiguration);
nominalManualMetrics = rrm.metrics.evaluate( ...
    nominalManualResult,simulationOptions.successCriteria);
nominalOptimizedMetrics = rrm.metrics.evaluate( ...
    nominalOptimizedResult,simulationOptions.successCriteria);

validationManualResult = rrm.simulation.runPid( ...
    validationRobot,manualController,reference,simulationOptions);
validationOptimizedResult = rrm.simulation.runPid( ...
    validationRobot,optimizedController,reference,simulationOptions);
[validationManualObjective,validationManualComponents] = ...
    rrm.optimization.scorePidResult(validationManualResult, ...
    validationRobot,reference,optimizationConfiguration);
[validationOptimizedObjective,validationOptimizedComponents] = ...
    rrm.optimization.scorePidResult(validationOptimizedResult, ...
    validationRobot,reference,optimizationConfiguration);
validationManualMetrics = rrm.metrics.evaluate( ...
    validationManualResult,simulationOptions.successCriteria);
validationOptimizedMetrics = rrm.metrics.evaluate( ...
    validationOptimizedResult,simulationOptions.successCriteria);

save(fullfile(dataDirectory,"pid_optimization.mat"), ...
    "trainingRobot","validationRobot","manualController", ...
    "optimizedController","optimizationConfiguration", ...
    "simulationOptions","reference","optimizationReport", ...
    "nominalManualResult","nominalOptimizedResult", ...
    "nominalManualObjective","nominalOptimizedObjective", ...
    "nominalManualComponents","nominalOptimizedComponents", ...
    "nominalManualMetrics","nominalOptimizedMetrics", ...
    "validationManualResult","validationOptimizedResult", ...
    "validationManualObjective","validationOptimizedObjective", ...
    "validationManualComponents","validationOptimizedComponents", ...
    "validationManualMetrics","validationOptimizedMetrics");

objectiveFigure = figure("Visible","off","Color","white");
objectiveValues = [optimizationReport.history.objective];
scatter(1:numel(objectiveValues),objectiveValues,18,[0.55 0.55 0.55], ...
    "filled");
hold on;
plot(cummin(objectiveValues),"LineWidth",1.8);
grid on;
xlabel("Objective evaluation");
ylabel("J (dimensionless)");
legend("Evaluated","Best so far","Location","best");
title("fmincon PID Tuning Objective History");
writeFigure(objectiveFigure,figureDirectory,"objective");

nominalTrackingFigure = errorComparisonFigure( ...
    nominalManualResult,nominalOptimizedResult, ...
    "Nominal 0.5 kg Tracking Error");
writeFigure(nominalTrackingFigure,figureDirectory,"nominal_tracking");

nominalTorqueFigure = figure("Visible","off","Color","white");
torqueLayout = tiledlayout(nominalTorqueFigure,2,1, ...
    "TileSpacing","compact","Padding","compact");
for jointIndex = 1:2
    axisHandle = nexttile(torqueLayout);
    plot(axisHandle,nominalManualResult.time, ...
        nominalManualResult.tau(jointIndex,:),"LineWidth",1.15);
    hold(axisHandle,"on");
    plot(axisHandle,nominalOptimizedResult.time, ...
        nominalOptimizedResult.tau(jointIndex,:),"LineWidth",1.15);
    yline(axisHandle,trainingRobot.torqueLimits(jointIndex),"--r","Limit");
    yline(axisHandle,-trainingRobot.torqueLimits(jointIndex),"--r");
    ylim(axisHandle,1.05*[-trainingRobot.torqueLimits(jointIndex), ...
        trainingRobot.torqueLimits(jointIndex)]);
    grid(axisHandle,"on");
    ylabel(axisHandle,sprintf("tau_%d (N m)",jointIndex));
    legend(axisHandle,"Manual PID","Optimized PID","Location","best");
end
xlabel(nexttile(torqueLayout,2),"Time (s)");
title(torqueLayout,"Nominal Applied Torque with Common Limits");
writeFigure(nominalTorqueFigure,figureDirectory,"nominal_torque");

validationTrackingFigure = errorComparisonFigure( ...
    validationManualResult,validationOptimizedResult, ...
    "Held-Out 0.8 kg Payload Tracking Error");
writeFigure(validationTrackingFigure,figureDirectory,"validation_tracking");

gainFigure = figure("Visible","off","Color","white");
gainLayout = tiledlayout(gainFigure,3,1, ...
    "TileSpacing","compact","Padding","compact");
gainNames = ["Kp","Ki","Kd"];
for gainIndex = 1:numel(gainNames)
    axisHandle = nexttile(gainLayout);
    gainName = gainNames(gainIndex);
    bar(axisHandle,[manualController.(gainName), ...
        optimizedController.(gainName)]);
    grid(axisHandle,"on");
    ylabel(axisHandle,gainName);
    xticks(axisHandle,1:2);
    xticklabels(axisHandle,["Joint 1","Joint 2"]);
    legend(axisHandle,"Manual PID","Optimized PID","Location","best");
end
title(gainLayout,"Manual and Optimization-Tuned Physical Gains");
writeFigure(gainFigure,figureDirectory,"gains");

scenario = repelem(["Nominal 0.5 kg";"Held-out 0.8 kg"],4);
controllerName = repmat(repelem(["Manual";"Optimized"],2),2,1);
joint = repmat((1:2).',4,1);
steadyRms = [nominalManualMetrics.steadyStateRmsError; ...
    nominalOptimizedMetrics.steadyStateRmsError; ...
    validationManualMetrics.steadyStateRmsError; ...
    validationOptimizedMetrics.steadyStateRmsError];
wholeRms = [nominalManualMetrics.rmsError; ...
    nominalOptimizedMetrics.rmsError;validationManualMetrics.rmsError; ...
    validationOptimizedMetrics.rmsError];
torqueRms = [nominalManualMetrics.controlRms; ...
    nominalOptimizedMetrics.controlRms;validationManualMetrics.controlRms; ...
    validationOptimizedMetrics.controlRms];
disp(table(scenario,controllerName,joint,wholeRms,steadyRms,torqueRms, ...
    VariableNames=["Scenario","Controller","Joint","RmsErrorRad", ...
    "SteadyRmsRad","TorqueRmsNm"]));
fprintf("fmincon exit flag: %d; iterations: %d; evaluations: %d\n", ...
    optimizationReport.exitFlag,optimizationReport.solverOutput.iterations, ...
    optimizationReport.solverOutput.funcCount);
fprintf("Initial/final objective: %.8g / %.8g (%.3f%% change)\n", ...
    nominalManualObjective,nominalOptimizedObjective, ...
    100*(nominalOptimizedObjective/nominalManualObjective-1));
fprintf("Final gains Kp=[%.6g %.6g], Ki=[%.6g %.6g], Kd=[%.6g %.6g]\n", ...
    optimizedController.Kp,optimizedController.Ki,optimizedController.Kd);

validationErrorRatio = mean(validationOptimizedMetrics.rmsError) / ...
    mean(validationManualMetrics.rmsError);
assert(nominalOptimizedObjective <= 0.98*nominalManualObjective, ...
    "rrm:experiment:InsufficientOptimization", ...
    "Optimized nominal objective did not improve by at least 2 percent.");
assert(nominalOptimizedMetrics.success && ...
    all(nominalOptimizedMetrics.saturationTime == 0), ...
    "rrm:experiment:NominalOptimizationFailure", ...
    "Optimized nominal PID failed common success or saturation criteria.");
assert(validationOptimizedMetrics.success && ...
    all(validationOptimizedMetrics.saturationTime == 0) && ...
    validationErrorRatio <= 1.10, ...
    "rrm:experiment:HeldOutValidationFailure", ...
    "Frozen optimized PID failed held-out payload criteria.");

function figureHandle = errorComparisonFigure(manualResult,optimizedResult,titleText)
figureHandle = figure("Visible","off","Color","white");
layout = tiledlayout(figureHandle,2,1, ...
    "TileSpacing","compact","Padding","compact");
for joint = 1:2
    axisHandle = nexttile(layout);
    plot(axisHandle,manualResult.time,rad2deg( ...
        manualResult.qReference(joint,:)-manualResult.q(joint,:)), ...
        "LineWidth",1.15);
    hold(axisHandle,"on");
    plot(axisHandle,optimizedResult.time,rad2deg( ...
        optimizedResult.qReference(joint,:)-optimizedResult.q(joint,:)), ...
        "LineWidth",1.15);
    yline(axisHandle,0,":k");
    grid(axisHandle,"on");
    ylabel(axisHandle,sprintf("e_%d (deg)",joint));
    legend(axisHandle,"Manual PID","Optimized PID","Location","best");
end
xlabel(nexttile(layout,2),"Time (s)");
title(layout,titleText);
end

function writeFigure(figureHandle,figureDirectory,suffix)
exportgraphics(figureHandle,fullfile(figureDirectory, ...
    "pid_optimization_" + suffix + ".png"),"Resolution",180);
close(figureHandle);
end
