%RUN_MULTIBODY_CROSS_VALIDATION Validate MATLAB against a physical model.
projectRoot = fileparts(fileparts(mfilename("fullpath")));
addpath(projectRoot);
if ~exist("outputRoot","var")
    outputRoot = fullfile(projectRoot,"results");
end
if ~exist("multibodyValidationMode","var")
    multibodyValidationMode = "full";
end
if ~any(multibodyValidationMode == ["full","smoke"])
    error("rrm:experiment:InvalidMultibodyValidationMode", ...
        "Multibody validation mode must be full or smoke.");
end

dataDirectory = fullfile(outputRoot,"data");
figureDirectory = fullfile(outputRoot,"figures");
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

robot = rrm.config.makeRobot("baseline");
simulationOptions = rrm.config.makeSimulationOptions();
if multibodyValidationMode == "full"
    moveDuration = 3;
    totalDuration = 5;
else
    moveDuration = 0.08;
    totalDuration = 0.12;
end
reference = rrm.trajectory.quintic( ...
    [0;0],deg2rad([45;60]),moveDuration, ...
    simulationOptions.sampleTime,totalDuration);
modelPath = fullfile(projectRoot,"models", ...
    "rrm_multibody_cross_validation.slx");
if ~isfile(modelPath)
    rrm.multibody.buildCrossValidationModel(modelPath);
end

controllerDefinitions = struct( ...
    "name",{"manual-pid","optimization-pid"}, ...
    "controller",{rrm.config.makePidController(robot), ...
    rrm.config.makeOptimizedPidController(robot)});

emptyRun = struct( ...
    "controllerName","", ...
    "controller",struct(), ...
    "matlabResult",struct(), ...
    "multibodyResult",struct(), ...
    "comparison",struct(), ...
    "matlabMetrics",struct(), ...
    "multibodyMetrics",struct());
runs = repmat(emptyRun,numel(controllerDefinitions),1);
emptyRow = struct( ...
    "Controller","", ...
    "MatlabStatus","", ...
    "MultibodyStatus","", ...
    "AgreementPass",false, ...
    "MultibodyTrackingSuccess",false, ...
    "QRmsJ1",NaN,"QRmsJ2",NaN, ...
    "QMaxJ1",NaN,"QMaxJ2",NaN, ...
    "DqRmsJ1",NaN,"DqRmsJ2",NaN, ...
    "DqMaxJ1",NaN,"DqMaxJ2",NaN, ...
    "TauRmsJ1",NaN,"TauRmsJ2",NaN, ...
    "TauMaxJ1",NaN,"TauMaxJ2",NaN, ...
    "EndEffectorRms",NaN,"EndEffectorMax",NaN, ...
    "MaximumOutOfPlane",NaN, ...
    "MatlabSaturationJ1",NaN,"MatlabSaturationJ2",NaN, ...
    "MultibodySaturationJ1",NaN,"MultibodySaturationJ2",NaN, ...
    "MultibodySteadyRmsJ1",NaN,"MultibodySteadyRmsJ2",NaN, ...
    "MultibodySteadyMaxJ1",NaN,"MultibodySteadyMaxJ2",NaN);
rows = repmat(emptyRow,numel(controllerDefinitions),1);

for index = 1:numel(controllerDefinitions)
    definition = controllerDefinitions(index);
    matlabResult = rrm.simulation.runController( ...
        robot,definition.controller,reference,simulationOptions);
    multibodyResult = rrm.multibody.runCrossValidation( ...
        robot,definition.controller,reference,simulationOptions,modelPath);
    comparison = rrm.multibody.compareRuns( ...
        matlabResult,multibodyResult,robot);
    matlabMetrics = rrm.metrics.evaluate( ...
        matlabResult,simulationOptions.successCriteria);
    multibodyMetrics = rrm.metrics.evaluate( ...
        multibodyResult,simulationOptions.successCriteria);
    runs(index) = struct( ...
        "controllerName",definition.name, ...
        "controller",definition.controller, ...
        "matlabResult",matlabResult, ...
        "multibodyResult",multibodyResult, ...
        "comparison",comparison, ...
        "matlabMetrics",matlabMetrics, ...
        "multibodyMetrics",multibodyMetrics);
    rows(index) = makeRow(definition.name,matlabResult, ...
        multibodyResult,comparison,multibodyMetrics);
end
runTable = struct2table(rows);

save(fullfile(dataDirectory,"multibody_cross_validation.mat"), ...
    "multibodyValidationMode","robot","simulationOptions", ...
    "reference","modelPath","controllerDefinitions","runs","runTable");
writetable(runTable,fullfile(dataDirectory, ...
    "multibody_cross_validation_runs.csv"));

writeFigure(trackingFigure(runs),figureDirectory,"tracking");
writeFigure(pathFigure(runs,robot),figureDirectory,"path");
writeFigure(torqueFigure(runs,robot),figureDirectory,"torque");
writeFigure(summaryFigure(runs),figureDirectory,"summary");
writeModelDiagram(modelPath,figureDirectory);

if multibodyValidationMode == "full"
    videoDirectory = fullfile(outputRoot,"videos");
    if ~isfolder(videoDirectory)
        mkdir(videoDirectory);
    end
    videoPath = fullfile(videoDirectory, ...
        "multibody_cross_validation_manual_pid.mp4");
    writeVideo(modelPath,videoPath,robot,controllerDefinitions(1).controller, ...
        reference,simulationOptions);
end

disp(runTable);
fprintf("Multibody validation mode: %s; runs: %d; agreements: %d\n", ...
    multibodyValidationMode,height(runTable),nnz(runTable.AgreementPass));
assert(height(runTable) == 2 && ...
    numel(unique(runTable.Controller)) == 2 && ...
    all(runTable.AgreementPass), ...
    "rrm:experiment:FailedMultibodyAgreement", ...
    "Both frozen PID controllers must pass Multibody cross-validation.");
if multibodyValidationMode == "full"
    assert(all(runTable.MultibodyTrackingSuccess), ...
        "rrm:experiment:FailedMultibodyTracking", ...
        "Formal Multibody runs must satisfy unchanged tracking criteria.");
end

function row = makeRow(name,matlabResult,multibodyResult,comparison,metrics)
row = struct( ...
    "Controller",name, ...
    "MatlabStatus",matlabResult.status, ...
    "MultibodyStatus",multibodyResult.status, ...
    "AgreementPass",comparison.pass, ...
    "MultibodyTrackingSuccess",metrics.success, ...
    "QRmsJ1",comparison.qRmsDifference(1), ...
    "QRmsJ2",comparison.qRmsDifference(2), ...
    "QMaxJ1",comparison.qMaxDifference(1), ...
    "QMaxJ2",comparison.qMaxDifference(2), ...
    "DqRmsJ1",comparison.dqRmsDifference(1), ...
    "DqRmsJ2",comparison.dqRmsDifference(2), ...
    "DqMaxJ1",comparison.dqMaxDifference(1), ...
    "DqMaxJ2",comparison.dqMaxDifference(2), ...
    "TauRmsJ1",comparison.tauRmsDifference(1), ...
    "TauRmsJ2",comparison.tauRmsDifference(2), ...
    "TauMaxJ1",comparison.tauMaxDifference(1), ...
    "TauMaxJ2",comparison.tauMaxDifference(2), ...
    "EndEffectorRms",comparison.endEffectorRmsDifference, ...
    "EndEffectorMax",comparison.endEffectorMaxDifference, ...
    "MaximumOutOfPlane",comparison.maximumOutOfPlanePosition, ...
    "MatlabSaturationJ1",comparison.matlabSaturationTime(1), ...
    "MatlabSaturationJ2",comparison.matlabSaturationTime(2), ...
    "MultibodySaturationJ1",comparison.multibodySaturationTime(1), ...
    "MultibodySaturationJ2",comparison.multibodySaturationTime(2), ...
    "MultibodySteadyRmsJ1",metrics.steadyStateRmsError(1), ...
    "MultibodySteadyRmsJ2",metrics.steadyStateRmsError(2), ...
    "MultibodySteadyMaxJ1",metrics.steadyStateMaxAbsError(1), ...
    "MultibodySteadyMaxJ2",metrics.steadyStateMaxAbsError(2));
end

function figureHandle = trackingFigure(runs)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 720]);
layout = tiledlayout(figureHandle,2,2, ...
    "TileSpacing","compact","Padding","compact");
for runIndex = 1:numel(runs)
    for joint = 1:2
        axisHandle = nexttile(layout);
        run = runs(runIndex);
        plot(axisHandle,run.matlabResult.time, ...
            rad2deg(run.matlabResult.qReference(joint,:)), ...
            ":k","LineWidth",1.5,"DisplayName","reference");
        hold(axisHandle,"on");
        plot(axisHandle,run.matlabResult.time, ...
            rad2deg(run.matlabResult.q(joint,:)), ...
            "LineWidth",1.3,"DisplayName","MATLAB RK4");
        plot(axisHandle,run.multibodyResult.time, ...
            rad2deg(run.multibodyResult.q(joint,:)), ...
            "--","LineWidth",1.1,"DisplayName","Multibody ode4");
        grid(axisHandle,"on");
        xlabel(axisHandle,"Time (s)");
        ylabel(axisHandle,sprintf("q_%d (deg)",joint));
        title(axisHandle,run.controllerName+" joint "+joint);
        legend(axisHandle,"Location","best");
    end
end
title(layout,"MATLAB and Simscape Multibody Joint Tracking");
end

function figureHandle = pathFigure(runs,robot)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1200 560]);
layout = tiledlayout(figureHandle,1,2, ...
    "TileSpacing","compact","Padding","compact");
reach = robot.L1+robot.L2;
for runIndex = 1:numel(runs)
    axisHandle = nexttile(layout);
    run = runs(runIndex);
    matlabPath = run.comparison.matlabEndEffectorPosition;
    multibodyPath = run.multibodyResult.endEffectorPosition;
    plot3(axisHandle,matlabPath(1,:),matlabPath(2,:),matlabPath(3,:), ...
        "LineWidth",2.0,"DisplayName","MATLAB kinematics");
    hold(axisHandle,"on");
    plot3(axisHandle,multibodyPath(1,:),multibodyPath(2,:), ...
        multibodyPath(3,:),"--","LineWidth",1.3, ...
        "DisplayName","Multibody sensor");
    scatter3(axisHandle,multibodyPath(1,1),multibodyPath(2,1), ...
        multibodyPath(3,1),45,"filled","DisplayName","start");
    scatter3(axisHandle,multibodyPath(1,end),multibodyPath(2,end), ...
        multibodyPath(3,end),55,"filled","DisplayName","end");
    grid(axisHandle,"on");
    xlim(axisHandle,[-0.1 1.05]*reach);
    ylim(axisHandle,[-0.2 1.05]*reach);
    zlim(axisHandle,[-0.1 0.1]*reach);
    daspect(axisHandle,[1 1 1]);
    view(axisHandle,[-42 28]);
    xlabel(axisHandle,"x (m)");
    ylabel(axisHandle,"y (m)");
    zlabel(axisHandle,"z (m)");
    title(axisHandle,run.controllerName);
    legend(axisHandle,"Location","southoutside", ...
        "Orientation","horizontal","NumColumns",2);
end
title(layout,"End-Effector Path Agreement");
end

function figureHandle = torqueFigure(runs,robot)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 720]);
layout = tiledlayout(figureHandle,2,2, ...
    "TileSpacing","compact","Padding","compact");
for runIndex = 1:numel(runs)
    for joint = 1:2
        axisHandle = nexttile(layout);
        run = runs(runIndex);
        plot(axisHandle,run.matlabResult.time, ...
            run.matlabResult.tau(joint,:),"LineWidth",1.3, ...
            "DisplayName","MATLAB RK4");
        hold(axisHandle,"on");
        plot(axisHandle,run.multibodyResult.time, ...
            run.multibodyResult.tau(joint,:),"--","LineWidth",1.1, ...
            "DisplayName","Multibody ode4");
        yline(axisHandle,robot.torqueLimits(joint),":k", ...
            "HandleVisibility","off");
        yline(axisHandle,-robot.torqueLimits(joint),":k", ...
            "HandleVisibility","off");
        grid(axisHandle,"on");
        xlabel(axisHandle,"Time (s)");
        ylabel(axisHandle,sprintf("tau_%d (N m)",joint));
        title(axisHandle,run.controllerName+" joint "+joint);
        legend(axisHandle,"Location","best");
    end
end
title(layout,"Applied Torque Agreement and Actuator Limits");
end

function figureHandle = summaryFigure(runs)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 460]);
layout = tiledlayout(figureHandle,1,2, ...
    "TileSpacing","compact","Padding","compact");
labels = ["q RMS","q max","dq RMS","tau RMS","EE RMS","EE max"];
for runIndex = 1:numel(runs)
    axisHandle = nexttile(layout);
    comparison = runs(runIndex).comparison;
    normalized = [ ...
        max(comparison.qRmsDifference)/comparison.thresholds.qRms; ...
        max(comparison.qMaxDifference)/comparison.thresholds.qMax; ...
        max(comparison.dqRmsDifference)/comparison.thresholds.dqRms; ...
        max(comparison.tauRmsDifference)/comparison.thresholds.tauRms; ...
        comparison.endEffectorRmsDifference / ...
        comparison.thresholds.endEffectorRms; ...
        comparison.endEffectorMaxDifference / ...
        comparison.thresholds.endEffectorMax];
    plotted = max(normalized,eps);
    bar(axisHandle,plotted,0.65);
    hold(axisHandle,"on");
    yline(axisHandle,1,"--r","acceptance boundary");
    set(axisHandle,"YScale","log");
    ylim(axisHandle,[1e-16 2]);
    xticks(axisHandle,1:numel(labels));
    xticklabels(axisHandle,labels);
    xtickangle(axisHandle,20);
    ylabel(axisHandle,"Measured difference / threshold");
    title(axisHandle,runs(runIndex).controllerName);
    grid(axisHandle,"on");
    for metric = 1:numel(normalized)
        text(axisHandle,metric,plotted(metric)*2, ...
            sprintf("%.1e",normalized(metric)), ...
            "HorizontalAlignment","center", ...
            "VerticalAlignment","bottom");
    end
end
title(layout,"Normalized Multibody Agreement Margin (< 1 passes)");
end

function writeFigure(figureHandle,figureDirectory,suffix)
exportgraphics(figureHandle,fullfile(figureDirectory, ...
    "multibody_cross_validation_"+suffix+".png"), ...
    "Resolution",300);
close(figureHandle);
end

function writeModelDiagram(modelPath,figureDirectory)
[~,modelName] = fileparts(modelPath);
load_system(modelPath);
cleanup = onCleanup(@() close_system(modelName,0));
set_param(modelName,"ZoomFactor","FitSystem");
fileName = fullfile(figureDirectory, ...
    "multibody_cross_validation_model.png");
print(char("-s"+modelName),"-dpng","-r180",fileName);
clear cleanup
end

function writeVideo(modelPath,videoPath,robot,controller,reference,options)
[~,modelName] = fileparts(modelPath);
load_system(modelPath);
cleanup = onCleanup(@() close_system(modelName,0));
workspace = get_param(modelName,"ModelWorkspace");
assignin(workspace,"rrmSampleTime",options.sampleTime);
assignin(workspace,"rrmStopTime",reference.time(end));
assignin(workspace,"rrmQReferenceSignal", ...
    timeseries(reference.q.',reference.time));
assignin(workspace,"rrmDqReferenceSignal", ...
    timeseries(reference.dq.',reference.time));
assignin(workspace,"rrmKp",controller.Kp);
assignin(workspace,"rrmKi",controller.Ki);
assignin(workspace,"rrmKd",controller.Kd);
assignin(workspace,"rrmDerivativeAlpha", ...
    exp(-2*pi*controller.derivativeFilterHz*options.sampleTime));
assignin(workspace,"rrmAntiWindupGain",controller.antiWindupGain);
assignin(workspace,"rrmTorqueLimits", ...
    min(controller.torqueLimits,robot.torqueLimits));
assignin(workspace,"rrmInitialQ",reference.q(:,1));
assignin(workspace,"rrmInitialDq",options.initialVelocity);
assignin(workspace,"rrmGravity",robot.gravity);
assignin(workspace,"rrmMbLinkLength",[robot.L1;robot.L2]);
assignin(workspace,"rrmMbLinkMass",[robot.m1;robot.m2]);
assignin(workspace,"rrmMbLinkInertia",robot.inertia);
assignin(workspace,"rrmMbPayload",robot.payload);
assignin(workspace,"rrmMbDamping",robot.viscousFriction);
assignin(workspace,"rrmMbWidth",0.06);
transverse = max(1e-6,0.01*robot.inertia);
assignin(workspace,"rrmMbMoments", ...
    [transverse robot.inertia robot.inertia]);
set_param(modelName,"StopTime",string(reference.time(end)), ...
    "FixedStep",string(options.sampleTime));
try
    smwritevideo(char(modelName),char(videoPath), ...
        "PlaybackSpeedRatio",1, ...
        "FrameRate",30, ...
        "VideoFormat","mpeg-4", ...
        "FrameSize",[1280 720]);
catch exception
    throwAsCaller(MException( ...
        "rrm:experiment:MultibodyVideoExportFailed", ...
        "Multibody video export failed: %s",exception.message));
end
file = dir(videoPath);
if numel(file) ~= 1 || file.bytes == 0
    error("rrm:experiment:MultibodyVideoExportFailed", ...
        "Multibody video export did not create a nonempty MP4 file.");
end
clear cleanup
end
