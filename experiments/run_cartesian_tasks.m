%RUN_CARTESIAN_TASKS Compare frozen controllers on Cartesian commands.
projectRoot = fileparts(fileparts(mfilename("fullpath")));
addpath(projectRoot);
if ~exist("outputRoot","var")
    outputRoot = fullfile(projectRoot,"results");
end
if ~exist("cartesianMode","var")
    cartesianMode = "full";
end
if ~any(cartesianMode == ["full","smoke"])
    error("rrm:experiment:InvalidCartesianMode", ...
        "Cartesian experiment mode must be full or smoke.");
end

dataDirectory = fullfile(outputRoot,"data");
figureDirectory = fullfile(outputRoot,"figures");
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

robot = rrm.config.makeRobot("baseline");
simulationOptions = rrm.config.makeSimulationOptions();
if cartesianMode == "smoke"
    simulationOptions.sampleTime = 0.005;
end
straightTask = makeStraightTask(robot,simulationOptions.sampleTime);
pickTask = rrm.trajectory.makePickAndPlaceTask( ...
    robot,simulationOptions.sampleTime);
tasks(1) = normalizeTask(straightTask);
tasks(2) = normalizeTask(pickTask);

controllerDefinitions(1) = struct("name","manual-pid", ...
    "controller",rrm.config.makePidController(robot));
controllerDefinitions(2) = struct("name","mamdani-fuzzy-pid", ...
    "controller",rrm.config.makeFuzzyPidController(robot));
controllerDefinitions(3) = struct("name","optimization-pid", ...
    "controller",rrm.config.makeOptimizedPidController(robot));

runCount = numel(tasks)*numel(controllerDefinitions);
runs = repmat(struct("taskName","","controllerName","", ...
    "result",struct(),"metrics",struct()),runCount,1);
rows = repmat(struct("Task","","Controller","","Status","", ...
    "Success",false,"CartesianRms",NaN,"CartesianMax",NaN, ...
    "PickupError",NaN,"PlaceError",NaN,"JointRmsMean",NaN, ...
    "TorqueRmsMean",NaN,"TotalSaturationTime",NaN),runCount,1);
runIndex = 0;
for taskIndex = 1:numel(tasks)
    task = tasks(taskIndex);
    for controllerIndex = 1:numel(controllerDefinitions)
        runIndex = runIndex+1;
        definition = controllerDefinitions(controllerIndex);
        result = rrm.simulation.runController( ...
            robot,definition.controller,task.reference,simulationOptions);
        metrics = rrm.metrics.evaluateCartesianTask( ...
            result,robot,task.reference,task.evaluationIndices);
        runs(runIndex) = struct( ...
            "taskName",task.name, ...
            "controllerName",definition.name, ...
            "result",result, ...
            "metrics",metrics);
        rows(runIndex) = struct( ...
            "Task",task.name, ...
            "Controller",definition.name, ...
            "Status",result.status, ...
            "Success",metrics.taskSuccess, ...
            "CartesianRms",metrics.cartesianRms, ...
            "CartesianMax",metrics.cartesianMax, ...
            "PickupError",metrics.pickupError, ...
            "PlaceError",metrics.placeError, ...
            "JointRmsMean",mean(metrics.rmsError), ...
            "TorqueRmsMean",mean(metrics.controlRms), ...
            "TotalSaturationTime",metrics.totalSaturationTime);
    end
end
runTable = struct2table(rows);

save(fullfile(dataDirectory,"cartesian_tasks.mat"), ...
    "cartesianMode","robot","simulationOptions","tasks", ...
    "controllerDefinitions","runs","runTable");
writetable(runTable,fullfile(dataDirectory,"cartesian_tasks_runs.csv"));

writeFigure(pathsFigure(tasks,runs),figureDirectory,"paths");
writeFigure(errorsFigure(tasks,runs),figureDirectory,"errors");
writeFigure(jointReferencesFigure(tasks), ...
    figureDirectory,"joint_references");
writeFigure(torqueFigure(tasks,runs,robot),figureDirectory,"torque");
writeFigure(summaryFigure(runTable),figureDirectory,"summary");

disp(runTable);
fprintf("Cartesian task mode: %s; runs: %d; successes: %d\n", ...
    cartesianMode,height(runTable),nnz(runTable.Success));
assert(height(runTable) == 6 && ...
    numel(unique(runTable.Task+"|"+runTable.Controller)) == 6, ...
    "rrm:experiment:IncompleteCartesianStudy", ...
    "Cartesian study must contain six unique task-controller runs.");
finiteColumns = ["CartesianRms","CartesianMax","JointRmsMean", ...
    "TorqueRmsMean","TotalSaturationTime"];
assert(all(isfinite(runTable{:,finiteColumns}),"all"), ...
    "rrm:experiment:InvalidCartesianMetric", ...
    "Every Cartesian task run must retain finite common metrics.");
for taskName = unique(runTable.Task,"stable").'
    taskRuns = runs([runs.taskName] == taskName);
    for comparison = 2:numel(taskRuns)
        assert(isequal(taskRuns(comparison).result.qReference, ...
            taskRuns(1).result.qReference) && ...
            isequal(taskRuns(comparison).result.dqReference, ...
            taskRuns(1).result.dqReference), ...
            "rrm:experiment:UnfairCartesianReference", ...
            "Controllers within a task must share an identical reference.");
    end
end

function task = makeStraightTask(robot,sampleTime)
path = rrm.trajectory.cartesianQuintic( ...
    [0.55;0.12],[0.22;0.48],3,sampleTime,4);
[solutions,reachable] = rrm.kinematics.inverse(robot,path.position(:,1));
if ~reachable
    error("rrm:trajectory:UnreachableCartesianPoint", ...
        "The prescribed straight-path start point is unreachable.");
end
reference = rrm.trajectory.cartesianToJoint( ...
    robot,path,solutions(:,1));
task = struct( ...
    "name","straight-line", ...
    "waypointNames",["start";"finish"], ...
    "waypoints",[[0.55;0.12],[0.22;0.48]], ...
    "moveDurations",3, ...
    "dwellDurations",1, ...
    "path",path, ...
    "reference",reference, ...
    "evaluationIndices",struct());
end

function normalized = normalizeTask(task)
normalized = struct( ...
    "name",task.name, ...
    "waypointNames",task.waypointNames, ...
    "waypoints",task.waypoints, ...
    "moveDurations",task.moveDurations, ...
    "dwellDurations",task.dwellDurations, ...
    "path",task.path, ...
    "reference",task.reference, ...
    "evaluationIndices",task.evaluationIndices);
end

function figureHandle = pathsFigure(tasks,runs)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 480]);
layout = tiledlayout(figureHandle,1,2, ...
    "TileSpacing","compact","Padding","compact");
for taskIndex = 1:numel(tasks)
    axisHandle = nexttile(layout);
    hold(axisHandle,"on");
    task = tasks(taskIndex);
    plot(axisHandle,task.path.position(1,:),task.path.position(2,:), ...
        "--k","LineWidth",2,"DisplayName","desired");
    taskRuns = runs([runs.taskName] == task.name);
    for runIndex = 1:numel(taskRuns)
        actual = taskRuns(runIndex).metrics.actualPosition;
        plot(axisHandle,actual(1,:),actual(2,:),"LineWidth",1.25, ...
            "DisplayName",taskRuns(runIndex).controllerName);
    end
    scatter(axisHandle,task.waypoints(1,:),task.waypoints(2,:), ...
        32,"filled","MarkerFaceColor","black", ...
        "DisplayName","waypoints");
    axis(axisHandle,"equal");
    grid(axisHandle,"on");
    xlabel(axisHandle,"x (m)");
    ylabel(axisHandle,"y (m)");
    title(axisHandle,task.name);
    legend(axisHandle,"Location","best");
end
title(layout,"Desired and Executed Cartesian Paths");
end

function figureHandle = errorsFigure(tasks,runs)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1000 720]);
layout = tiledlayout(figureHandle,2,1, ...
    "TileSpacing","compact","Padding","compact");
for taskIndex = 1:numel(tasks)
    axisHandle = nexttile(layout);
    hold(axisHandle,"on");
    taskRuns = runs([runs.taskName] == tasks(taskIndex).name);
    for runIndex = 1:numel(taskRuns)
        plot(axisHandle,taskRuns(runIndex).result.time, ...
            taskRuns(runIndex).metrics.cartesianError, ...
            "LineWidth",1.25, ...
            "DisplayName",taskRuns(runIndex).controllerName);
    end
    grid(axisHandle,"on");
    xlabel(axisHandle,"Time (s)");
    ylabel(axisHandle,"EE error (m)");
    title(axisHandle,tasks(taskIndex).name);
    legend(axisHandle,"Location","best");
end
title(layout,"Cartesian Tracking Error");
end

function figureHandle = jointReferencesFigure(tasks)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 720]);
layout = tiledlayout(figureHandle,2,2, ...
    "TileSpacing","compact","Padding","compact");
for taskIndex = 1:numel(tasks)
    for joint = 1:2
        axisHandle = nexttile(layout);
        plot(axisHandle,tasks(taskIndex).reference.time, ...
            rad2deg(tasks(taskIndex).reference.q(joint,:)), ...
            "LineWidth",1.4);
        grid(axisHandle,"on");
        xlabel(axisHandle,"Time (s)");
        ylabel(axisHandle,sprintf("q_%d (deg)",joint));
        title(axisHandle,tasks(taskIndex).name+" joint "+joint);
    end
end
title(layout,"Continuous Joint References from Cartesian Commands");
end

function figureHandle = torqueFigure(tasks,runs,robot)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1100 720]);
layout = tiledlayout(figureHandle,2,2, ...
    "TileSpacing","compact","Padding","compact");
for taskIndex = 1:numel(tasks)
    taskRuns = runs([runs.taskName] == tasks(taskIndex).name);
    for joint = 1:2
        axisHandle = nexttile(layout);
        hold(axisHandle,"on");
        for runIndex = 1:numel(taskRuns)
            plot(axisHandle,taskRuns(runIndex).result.time, ...
                taskRuns(runIndex).result.tau(joint,:), ...
                "LineWidth",1,"DisplayName", ...
                taskRuns(runIndex).controllerName);
        end
        yline(axisHandle,robot.torqueLimits(joint),"--k", ...
            "HandleVisibility","off");
        yline(axisHandle,-robot.torqueLimits(joint),"--k", ...
            "HandleVisibility","off");
        grid(axisHandle,"on");
        xlabel(axisHandle,"Time (s)");
        ylabel(axisHandle,sprintf("tau_%d (N m)",joint));
        title(axisHandle,tasks(taskIndex).name+" joint "+joint);
        legend(axisHandle,"Location","best");
    end
end
title(layout,"Applied Joint Torque and Limits");
end

function figureHandle = summaryFigure(runTable)
figureHandle = figure("Visible","off","Color","white", ...
    "Position",[100 100 1200 480]);
layout = tiledlayout(figureHandle,1,3, ...
    "TileSpacing","compact","Padding","compact");
variables = ["CartesianRms","CartesianMax","TotalSaturationTime"];
yLabels = ["Cartesian RMS (m)","Cartesian max (m)", ...
    "Joint-summed saturation (s)"];
tasks = unique(runTable.Task,"stable");
controllers = unique(runTable.Controller,"stable");
for variableIndex = 1:numel(variables)
    axisHandle = nexttile(layout);
    values = zeros(numel(tasks),numel(controllers));
    for taskIndex = 1:numel(tasks)
        for controllerIndex = 1:numel(controllers)
            row = runTable.Task == tasks(taskIndex) & ...
                runTable.Controller == controllers(controllerIndex);
            values(taskIndex,controllerIndex) = ...
                runTable.(variables(variableIndex))(row);
        end
    end
    bar(axisHandle,values);
    xticks(axisHandle,1:numel(tasks));
    xticklabels(axisHandle,tasks);
    xtickangle(axisHandle,20);
    ylabel(axisHandle,yLabels(variableIndex));
    grid(axisHandle,"on");
    legend(axisHandle,controllers,"Location","best");
end
title(layout,"Cartesian Task Summary");
end

function writeFigure(figureHandle,figureDirectory,suffix)
exportgraphics(figureHandle,fullfile(figureDirectory, ...
    "cartesian_tasks_"+suffix+".png"),"Resolution",180);
close(figureHandle);
end
